// Envia um comando ao display
static void enviar_comando(uint8_t comando)
{
    uint8_t dados[2] = {CONTROLE_COMANDO, comando};
    i2c_write_blocking(TELA_I2C, TELA_ENDERECO, dados, 2, false);
}

// Acende um pixel do buffer (ignora posições fora da tela)
static void acender_pixel(int x, int y)
{
    if (x < 0 || x >= TELA_LARGURA || y < 0 || y >= TELA_ALTURA)
        return;
    pixels[(y / 8) * TELA_LARGURA + x] |= 1 << (y % 8);
}

// Desenha um caractere com o canto superior esquerdo em (x, y). Na escala 2,
// cada pixel da fonte vira um quadrado de 2x2, e assim por diante
static void desenhar_caractere(int x, int y, char c, int escala)
{
    if (c < ' ' || c > '~')
        c = '?';
    const uint8_t *colunas = fonte[c - ' '];
    for (int coluna = 0; coluna < 5; coluna++)
        for (int linha = 0; linha < 7; linha++)
            if (colunas[coluna] & (1 << linha))
                for (int dx = 0; dx < escala; dx++)
                    for (int dy = 0; dy < escala; dy++)
                        acender_pixel(x + coluna * escala + dx, y + linha * escala + dy);
}

void tela_iniciar(void)
{
    // I2C a 400 kHz, com pull-up nos pinos
    i2c_init(TELA_I2C, TELA_FREQUENCIA_HZ);
    gpio_set_function(TELA_SDA, GPIO_FUNC_I2C);
    gpio_set_function(TELA_SCL, GPIO_FUNC_I2C);
    gpio_pull_up(TELA_SDA);
    gpio_pull_up(TELA_SCL);

    // Sequência de inicialização padrão do SSD1306 128x64
    static const uint8_t comandos[] = {
        0xAE,       // desliga o display durante a configuração
        0xD5, 0x80, // frequência do clock interno
        0xA8, 0x3F, // 64 linhas
        0xD3, 0x00, // sem deslocamento vertical
        0x40,       // começa a desenhar na linha 0
        0x8D, 0x14, // liga o conversor de tensão interno
        0x20, 0x00, // endereçamento horizontal: os bytes preenchem a tela em sequência
        0xA1,       // inverte a ordem das colunas e
        0xC8,       // das linhas: com os dois, a imagem fica na posição certa no módulo
        0xDA, 0x12, // configuração dos pinos de linha para 128x64
        0x81, 0xCF, // contraste
        0xD9, 0xF1, // tempo de pré-carga
        0xDB, 0x40, // nível de tensão de desligamento dos pixels
        0xA4,       // mostra o conteúdo da memória
        0xA6,       // modo normal (pixel aceso = 1)
        0x2E,       // sem rolagem
        0xAF,       // liga o display
    };
    for (size_t i = 0; i < sizeof(comandos); i++)
        enviar_comando(comandos[i]);

    buffer[0] = CONTROLE_DADOS;
    tela_limpar();
    tela_atualizar();
}

void tela_limpar(void)
{
    memset(pixels, 0, TELA_LARGURA * TELA_ALTURA / 8);
}

void tela_escrever_centralizado(int y, const char *texto, int escala)
{
    // Cada caractere ocupa 6 colunas (5 da letra + 1 de espaço)
    int largura = (int)strlen(texto) * 6 * escala - escala;
    int x = (TELA_LARGURA - largura) / 2;
    for (; *texto; texto++, x += 6 * escala)
        desenhar_caractere(x, y, *texto, escala);
}

void tela_linha_horizontal(int y)
{
    for (int x = 0; x < TELA_LARGURA; x++)
        acender_pixel(x, y);
}

void tela_atualizar(void)
{
    // Define a área de escrita como a tela inteira (colunas 0-127, páginas
    // 0-7) e envia todos os pixels de uma vez
    enviar_comando(0x21);
    enviar_comando(0);
    enviar_comando(TELA_LARGURA - 1);
    enviar_comando(0x22);
    enviar_comando(0);
    enviar_comando(TELA_ALTURA / 8 - 1);
    i2c_write_blocking(TELA_I2C, TELA_ENDERECO, buffer, sizeof(buffer), false);
}
